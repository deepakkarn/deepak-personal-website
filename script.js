const toggle = document.getElementById('language-toggle');
const label = document.getElementById('language-label');
const menu = document.getElementById('menu-toggle');
const mobile = document.getElementById('mobile-nav');
const heading = document.getElementById('hero-title');

function setLanguage(lang) {
  const dict = content[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const value = dict[el.dataset.i18n];
    if (value !== undefined) {
      if (/Title$/.test(el.dataset.i18n) || ['memoryTitle','connectTitle','aboutTitle','focusTitle','journeyTitle'].includes(el.dataset.i18n)) {
        el.innerHTML = value;
      } else {
        el.textContent = value;
      }
    }
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => {
    const value = dict[el.dataset.i18nAlt];
    if (value !== undefined) el.alt = value;
  });
  label.textContent = lang === 'ne' ? 'EN' : 'ने';
  toggle.setAttribute('aria-pressed', String(lang === 'ne'));
  toggle.setAttribute('aria-label', lang === 'ne' ? 'Switch to English' : 'नेपालीमा परिवर्तन गर्नुहोस्');
  syncName();
  document.dispatchEvent(new CustomEvent('dk:languagechange', { detail: { language: lang } }));
  try { localStorage.setItem('dk-language', lang); } catch (e) {}
}

function syncName() {
  heading.innerHTML = document.documentElement.lang === 'ne'
    ? 'दीपक कुमार<br>कर्ण<span class="name-en">Deepak Kumar Karn</span>'
    : 'Deepak Kumar<br><em>Karn.</em><span class="name-en">दीपक कुमार कर्ण</span>';
}

let starting = 'en';
try { if (localStorage.getItem('dk-language') === 'ne') starting = 'ne'; } catch (e) {}
setLanguage(starting);

toggle.addEventListener('click', () => setLanguage(document.documentElement.lang === 'ne' ? 'en' : 'ne'));
menu.addEventListener('click', () => {
  const open = menu.getAttribute('aria-expanded') === 'true';
  menu.setAttribute('aria-expanded', String(!open));
  menu.setAttribute('aria-label', open ? 'Open menu' : 'Close menu');
  mobile.hidden = open;
});
mobile.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
  mobile.hidden = true;
  menu.setAttribute('aria-expanded', 'false');
  menu.setAttribute('aria-label', 'Open menu');
}));
// Escape closes the mobile navigation and returns focus to its opener.
document.addEventListener('keydown', event => {
  if (event.key !== 'Escape' || mobile.hidden) return;
  mobile.hidden = true;
  menu.setAttribute('aria-expanded', 'false');
  menu.setAttribute('aria-label', 'Open menu');
  menu.focus();
});

// The anchor is outside the sticky header, so native hash navigation
// also returns to the actual page top when JavaScript is disabled or cached.
const pageTop = document.getElementById('page-top');
document.querySelectorAll('a.wordmark[href="#page-top"], a.footer-name[href="#page-top"]').forEach(link => {
  link.addEventListener('click', event => {
    if (!pageTop) return; // Native anchor fallback
    event.preventDefault();
    const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    pageTop.scrollIntoView({ block: 'start', behavior: reduceMotion ? 'auto' : 'smooth' });
  });
});

