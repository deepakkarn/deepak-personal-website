const bandPhotos = Array.from(document.querySelectorAll('.band-photo:not([aria-hidden="true"])'));
const lightbox = document.getElementById('lightbox');
const lightboxImage = document.getElementById('lightbox-image');
const lightboxClose = document.getElementById('lightbox-close');
const lightboxBackdrop = document.querySelector('.lightbox-backdrop');
let lightboxTrigger = null;

function getTranslation(key) {
  const lang = document.documentElement.lang === 'en' ? 'en' : 'ne';
  return content[lang]?.[key] || '';
}

function openLightbox(button) {
  if (!lightbox || !lightboxImage || !button) return;
  lightboxTrigger = button;
  lightboxImage.src = button.dataset.full;
  const altKey = button.dataset.altKey;
  lightboxImage.alt = altKey ? getTranslation(altKey) : '';
  lightbox.hidden = false;
  document.body.classList.add('lightbox-open');
  lightboxClose?.focus();
}

function closeLightbox() {
  if (!lightbox || !lightboxImage) return;
  lightbox.hidden = true;
  lightboxImage.src = '';
  lightboxImage.alt = '';
  document.body.classList.remove('lightbox-open');
  if (lightboxTrigger?.isConnected) lightboxTrigger.focus();
  lightboxTrigger = null;
}

bandPhotos.forEach(button => {
  button.addEventListener('click', () => openLightbox(button));
});
lightboxClose?.addEventListener('click', closeLightbox);
lightboxBackdrop?.addEventListener('click', closeLightbox);
document.addEventListener('keydown', (event) => {
  if (!lightbox || lightbox.hidden) return;
  if (event.key === 'Escape') {
    event.preventDefault();
    closeLightbox();
  } else if (event.key === 'Tab') {
    // The close button is the sole keyboard control in this dialog.
    event.preventDefault();
    lightboxClose?.focus();
  }
});
